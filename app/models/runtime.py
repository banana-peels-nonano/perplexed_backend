"""Runtime tables: what happens during the event.

UUID primary keys, generated by Postgres (gen_random_uuid(), built in since PG 13),
so rows inserted by raw SQL or by the app get ids the same way.
Fairness rules live here as constraints wherever a constraint can express them.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    Numeric,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy import (
    text as sql_text,  # 'text' is also a column name below
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base


def _uuid_pk() -> Mapped[uuid.UUID]:
    return mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )


def _created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now())


class Event(Base):
    """One row per event. `config` holds the values organisers may change without a deploy:
    default quota, trust thresholds, evidence budget, model ids."""

    __tablename__ = "event"

    id: Mapped[uuid.UUID] = _uuid_pk()
    name: Mapped[str] = mapped_column(Text)
    case_id: Mapped[str] = mapped_column(Text)
    brief: Mapped[str] = mapped_column(Text, server_default=sql_text("''"))  # shown to all
    config: Mapped[dict] = mapped_column(JSONB, server_default=sql_text("'{}'::jsonb"))
    created_at: Mapped[datetime] = _created_at()


class Phase(Base):
    __tablename__ = "phase"
    __table_args__ = (
        UniqueConstraint("event_id", "seq", name="uq_phase_event_seq"),
        CheckConstraint("status IN ('scheduled', 'running', 'paused', 'ended')", name="status"),
        # at most one running-or-paused phase per event
        Index(
            "uq_phase_one_active",
            "event_id",
            unique=True,
            postgresql_where=sql_text("status IN ('running', 'paused')"),
        ),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    event_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("event.id"))
    key: Mapped[str] = mapped_column(Text)  # 'solo', 'joint', ... (matches case phases)
    display_name: Mapped[str] = mapped_column(Text)
    seq: Mapped[int] = mapped_column(Integer)
    status: Mapped[str] = mapped_column(Text, server_default=sql_text("'scheduled'"))
    planned_seconds: Mapped[int] = mapped_column(Integer)
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    paused_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    total_paused_seconds: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))
    extended_seconds: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))
    # e.g. {"interview": true, "alliance": false}
    capabilities: Mapped[dict] = mapped_column(JSONB, server_default=sql_text("'{}'::jsonb"))


class Team(Base):
    __tablename__ = "team"

    id: Mapped[uuid.UUID] = _uuid_pk()
    code: Mapped[str] = mapped_column(Text, unique=True)  # printed on the team's card
    name: Mapped[str] = mapped_column(Text)
    company_id: Mapped[str | None] = mapped_column(ForeignKey("company.id"), index=True)
    access_code_hash: Mapped[str] = mapped_column(Text)  # never the code itself
    max_sessions: Mapped[int] = mapped_column(Integer, server_default=sql_text("2"))
    created_at: Mapped[datetime] = _created_at()


class TeamSession(Base):
    """One row per logged-in laptop. Sessions are keys; all state hangs off the team."""

    __tablename__ = "team_session"

    id: Mapped[uuid.UUID] = _uuid_pk()
    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("team.id"), index=True)
    token_hash: Mapped[str] = mapped_column(Text, unique=True)
    device_label: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = _created_at()
    last_seen_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class TeamStakeholderState(Base):
    """Hidden per-(team, stakeholder) state: trust, quota, the in-flight guard.
    HR strikes and lockouts are per department: TeamDepartmentState."""

    __tablename__ = "team_stakeholder_state"
    __table_args__ = (
        CheckConstraint("trust BETWEEN 0 AND 100", name="trust_range"),
        CheckConstraint("questions_used >= 0 AND questions_used <= quota", name="quota"),
    )

    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("team.id"), primary_key=True)
    stakeholder_id: Mapped[str] = mapped_column(ForeignKey("stakeholder.id"), primary_key=True)
    trust: Mapped[int] = mapped_column(Integer, server_default=sql_text("50"))
    questions_used: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))
    quota: Mapped[int] = mapped_column(Integer)
    # set while a question is being answered; no FK to keep the two tables independent
    in_flight_message_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))
    version: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))


class TeamDepartmentState(Base):
    """HR, per (team, department): strikes towards a complaint and the lockout it causes.

    A complaint from one stakeholder closes the whole department to the team (checklist:
    "hostility counter per team per department", "10-minute department lockout").
    Rows are created on a team's first question to the department.
    """

    __tablename__ = "team_department_state"
    __table_args__ = (
        ForeignKeyConstraint(
            ["company_id", "department"],
            ["department.company_id", "department.name"],
            name="fk_team_department_state_department",
        ),
        CheckConstraint("strikes >= 0", name="strikes"),
    )

    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("team.id"), primary_key=True)
    company_id: Mapped[str] = mapped_column(Text, primary_key=True)
    department: Mapped[str] = mapped_column(Text, primary_key=True)
    strikes: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))
    locked_until: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class HrFlag(Base):
    """Every strike, kept for good: the organisers' log and interview-efficiency scoring.

    outcome: 'strike' (counted), 'warning' (one short of a complaint), 'lockout'.
    """

    __tablename__ = "hr_flag"
    __table_args__ = (
        CheckConstraint("outcome IN ('strike', 'warning', 'lockout')", name="outcome"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("team.id"), index=True)
    stakeholder_id: Mapped[str] = mapped_column(ForeignKey("stakeholder.id"))
    department: Mapped[str] = mapped_column(Text)
    message_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("message.id"))
    label: Mapped[str] = mapped_column(Text)
    outcome: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = _created_at()


class TeamTimeBonus(Base):
    """Extra seconds one team gets in one phase (organisers give time back after a crash).
    Only that team's clock and interview gate move; the phase itself doesn't."""

    __tablename__ = "team_time_bonus"
    __table_args__ = (CheckConstraint("seconds >= 0", name="seconds"),)

    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("team.id"), primary_key=True)
    phase_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("phase.id"), primary_key=True)
    seconds: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))


class Announcement(Base):
    """A broadcast from the organisers. company_id None = everyone (and the projector)."""

    __tablename__ = "announcement"

    id: Mapped[uuid.UUID] = _uuid_pk()
    event_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("event.id"))
    company_id: Mapped[str | None] = mapped_column(ForeignKey("company.id"))
    text: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = _created_at()
    retracted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class Message(Base):
    __tablename__ = "message"
    __table_args__ = (
        UniqueConstraint("team_id", "stakeholder_id", "seq", name="uq_message_thread_seq"),
        # idempotency: a retried request with the same id cannot create a second question
        UniqueConstraint("team_id", "client_request_id", name="uq_message_client_request"),
        CheckConstraint("role IN ('question', 'answer', 'notice')", name="role"),
        CheckConstraint("status IN ('pending', 'answered', 'failed', 'blocked')", name="status"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("team.id"))
    stakeholder_id: Mapped[str] = mapped_column(ForeignKey("stakeholder.id"))
    seq: Mapped[int] = mapped_column(Integer)  # order within the (team, stakeholder) thread
    role: Mapped[str] = mapped_column(Text)
    text: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text, server_default=sql_text("'answered'"))
    cited: Mapped[list[str]] = mapped_column(ARRAY(Text), server_default=sql_text("'{}'"))
    client_request_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))
    created_at: Mapped[datetime] = _created_at()
    # questions only: what the backend decided (label, trust change, evidence given, check
    # results). Organisers only: never sent to participants.
    meta: Mapped[dict | None] = mapped_column(JSONB)


class TeamDisclosure(Base):
    """Evidence a team has actually been shown. One row per (team, passage): the first time.

    Feeds unlock prerequisites, the team's evidence cards, and 'clues found' for judges.
    """

    __tablename__ = "team_disclosure"
    __table_args__ = (CheckConstraint("mode IN ('paraphrase', 'quote')", name="mode"),)

    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("team.id"), primary_key=True)
    passage_id: Mapped[str] = mapped_column(ForeignKey("passage.id"), primary_key=True)
    stakeholder_id: Mapped[str] = mapped_column(ForeignKey("stakeholder.id"))
    message_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("message.id"))
    mode: Mapped[str] = mapped_column(Text)
    disclosed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )


class TeamBoard(Base):
    """The team's evidence board (app/portal/board.py says what it may hold).

    One row per team. `version` is bumped on every save; a save based on an older version
    is refused, so two laptops editing at once can't silently overwrite each other.
    """

    __tablename__ = "team_board"
    __table_args__ = (CheckConstraint("version >= 1", name="version"),)

    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("team.id"), primary_key=True)
    version: Mapped[int] = mapped_column(Integer)
    doc: Mapped[dict] = mapped_column(JSONB)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class LlmCall(Base):
    """Every provider call: tokens, cost, latency. Cost monitoring is a SUM over this table."""

    __tablename__ = "llm_call"

    id: Mapped[uuid.UUID] = _uuid_pk()
    purpose: Mapped[str] = mapped_column(Text)  # 'classify' | 'answer'
    provider: Mapped[str] = mapped_column(Text)
    model: Mapped[str] = mapped_column(Text)
    team_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("team.id"))
    message_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))
    input_tokens: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))
    cache_read_tokens: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))
    cache_write_tokens: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))
    output_tokens: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))
    cost_usd: Mapped[Decimal] = mapped_column(Numeric(12, 6), server_default=sql_text("0"))
    latency_ms: Mapped[int] = mapped_column(Integer, server_default=sql_text("0"))
    status: Mapped[str] = mapped_column(Text)  # 'ok' | 'error'
    request_id: Mapped[str | None] = mapped_column(Text)
    error: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), index=True
    )
